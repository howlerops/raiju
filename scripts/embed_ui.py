#!/usr/bin/env python3
"""Embed ui/index.html into src/ui_assets.tov as a Tov string constant.

Tov cannot read files at build time, so the page is compiled in as
`export const INDEX_HTML: string = "..."`. Re-run this after every change to
ui/index.html.

Tov string literals accept raw UTF-8 and the escapes \\" \\\\ \\n \\r \\t and
\\xHH, but not \\uXXXX, so the escaper below emits only those forms.

Usage: scripts/embed_ui.py
"""
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "ui" / "index.html"
OUT = ROOT / "src" / "ui_assets.tov"


def tov_string(text):
    out = ['"']
    for ch in text:
        o = ord(ch)
        if ch == '"':
            out.append('\\"')
        elif ch == "\\":
            out.append("\\\\")
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        elif ch == "\t":
            out.append("\\t")
        elif o < 0x20 or o == 0x7F:
            out.append("\\x%02x" % o)
        elif o in (0x2028, 0x2029):
            # Raw line separators are not safe inside a Tov literal and
            # there is no escape for them here; keep the page free of them.
            raise SystemExit("ui/index.html contains U+%04X; remove it" % o)
        else:
            out.append(ch)
    out.append('"')
    return "".join(out)


def main():
    text = SRC.read_text(encoding="utf-8")
    body = (
        "// Generated by scripts/embed_ui.py from ui/index.html. Do not edit.\n"
        "export const INDEX_HTML: string = " + tov_string(text) + "\n"
    )
    OUT.write_text(body, encoding="utf-8")
    print("wrote %s (%d bytes of HTML)" % (OUT.relative_to(ROOT), len(text.encode("utf-8"))))


main()
