#!/usr/bin/env python3
"""Embed the built web UI (web/dist) into src/ui_assets.tov.

Tov cannot read files at build time, so every file of the Vite build is
compiled in as one row of `uiAssets()`:

  { path, type, etag, base64, body, gz }

path    the file's path under web/dist, no leading slash (index.html,
        assets/index-XXXX.js)
type    the Content-Type
etag    sha256 of the file, hex, in quotes
base64  true when body is the file's bytes in base64 (images, fonts);
        false when body is the file's text
body    the text or the base64
gz      for text files that shrink: the gzip of the file, in base64 (for
        clients that send Accept-Encoding: gzip); "" otherwise

The output is deterministic, so `make web-check` can rebuild and compare.

Tov string literals accept raw UTF-8 and the escapes \\" \\\\ \\n \\r \\t and
\\xHH, but not \\uXXXX, so the escaper below emits only those forms.

Usage: scripts/embed_ui.py [--check] [--dist DIR]
  --check  write nothing; exit 1 when src/ui_assets.tov would change
"""
import base64
import gzip
import hashlib
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "ui_assets.tov"

TEXT_TYPES = {
    ".html": "text/html; charset=utf-8",
    ".js": "text/javascript; charset=utf-8",
    ".mjs": "text/javascript; charset=utf-8",
    ".css": "text/css; charset=utf-8",
    ".json": "application/json; charset=utf-8",
    ".webmanifest": "application/manifest+json; charset=utf-8",
    ".svg": "image/svg+xml",
    ".txt": "text/plain; charset=utf-8",
    ".map": "application/json; charset=utf-8",
}
BINARY_TYPES = {
    ".png": "image/png",
    ".jpg": "image/jpeg",
    ".jpeg": "image/jpeg",
    ".gif": "image/gif",
    ".webp": "image/webp",
    ".ico": "image/x-icon",
    ".woff": "font/woff",
    ".woff2": "font/woff2",
    ".ttf": "font/ttf",
    ".otf": "font/otf",
}


def tov_string(text):
    out = ['"']
    for ch in text:
        o = ord(ch)
        if ch == '"':
            out.append('\\"')
        elif ch == "\\":
            out.append("\\\\")
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        elif ch == "\t":
            out.append("\\t")
        elif o < 0x20 or o == 0x7F:
            out.append("\\x%02x" % o)
        else:
            out.append(ch)
    out.append('"')
    return "".join(out)


def text_of(path, raw):
    try:
        text = raw.decode("utf-8")
    except UnicodeDecodeError:
        raise SystemExit("%s is not UTF-8 text" % path)
    # raw line separators are not safe inside a Tov literal; in JavaScript
    # and CSS source the escaped spelling means the same thing
    return text.replace("\u2028", "\\u2028").replace("\u2029", "\\u2029")


def rows(dist):
    files = sorted(p for p in dist.rglob("*") if p.is_file())
    if not files:
        raise SystemExit("%s is empty; run `bun run build` in web/ first" % dist)
    if not (dist / "index.html").is_file():
        raise SystemExit("%s has no index.html" % dist)
    out = []
    for f in files:
        rel = f.relative_to(dist).as_posix()
        ext = f.suffix.lower()
        raw = f.read_bytes()
        etag = '"%s"' % hashlib.sha256(raw).hexdigest()
        if ext in TEXT_TYPES:
            ctype, binary, body = TEXT_TYPES[ext], False, text_of(rel, raw)
            gz = ""
            if len(raw) > 1024:
                packed = gzip.compress(raw, 9, mtime=0)
                if len(packed) < len(raw) * 0.9:
                    gz = base64.b64encode(packed).decode("ascii")
        elif ext in BINARY_TYPES:
            ctype, binary, body, gz = BINARY_TYPES[ext], True, base64.b64encode(raw).decode("ascii"), ""
        else:
            raise SystemExit("%s: no content type known for %s; add it to embed_ui.py" % (rel, ext or "(no extension)"))
        out.append(
            "    { path: %s, type: %s, etag: %s, base64: %s, body: %s, gz: %s },"
            % (tov_string(rel), tov_string(ctype), tov_string(etag), "true" if binary else "false", tov_string(body), tov_string(gz))
        )
    return out


def main():
    args = sys.argv[1:]
    check = "--check" in args
    dist = ROOT / "web" / "dist"
    if "--dist" in args:
        dist = pathlib.Path(args[args.index("--dist") + 1]).resolve()
    lines = rows(dist)
    text = (
        "// Generated by scripts/embed_ui.py from web/dist (make web). Do not edit.\n"
        "// base64: body is the file's bytes in base64. gz: the gzip of a text file in base64, or empty.\n"
        "export type UiAsset = { path: string, type: string, etag: string, base64: boolean, body: string, gz: string }\n"
        "\n"
        "export function uiAssets(): UiAsset[] {\n"
        "  return [\n" + "\n".join(lines) + "\n  ]\n"
        "}\n"
    )
    if check:
        have = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if have != text:
            print("src/ui_assets.tov is out of date; run `make web` and commit it", file=sys.stderr)
            return 1
        print("web-check: src/ui_assets.tov is up to date (%d files)" % len(lines))
        return 0
    OUT.write_text(text, encoding="utf-8")
    print("wrote %s (%d files, %d bytes)" % (OUT.relative_to(ROOT), len(lines), len(text.encode("utf-8"))))
    return 0


sys.exit(main())
